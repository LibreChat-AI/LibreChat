export function getSteerErrorCode(error: unknown): SteerErrorCode | undefined {
  const response = (error as { response?: { data?: { code?: string } } } | undefined)?.response;
  return response?.data?.code;
}

export function isDefiniteSteerRejection(error: unknown): boolean {
  const status = (error as { response?: { status?: number } } | undefined)?.response?.status;
  return (
    status != null &&
    status >= 400 &&
    status < 500 &&
    // These statuses can be generated by an intermediary while the origin
    // request continues; keep their delivery outcome explicitly uncertain.
    status !== 408 &&
    status !== 425
  );
}

function isSameRunEpoch(a: RunEnd | null, b: RunEnd): boolean {
  if (a == null || a.conversationId !== b.conversationId) {
    return false;
  }
  if (a.generationCreatedAt != null || b.generationCreatedAt != null) {
    return a.generationCreatedAt === b.generationCreatedAt;
  }
  return a.endedAt === b.endedAt;
}

/**
 * Resolves a steer's 202 ACK against the applied-id set and the run's live
 * state: on the common path the local chip is swapped for its server-assigned
 * id (still `pending`, awaiting `on_steer_applied`). If an `on_steer_applied`
 * event already beat the ACK, if the source generation was replaced, or if the
 * run itself ended before the ACK landed, no later SSE event will ever resolve
 * a `pending` chip, so the caller is told to route the words into the queue
 * instead of stranding one.
 *
 * `ordinaryRunOver` is the caller's observation of ordinary terminal state
 * (the visible pane is idle); epoch replacement is derived here so every
 * caller applies the same rule.
 *
 * The single implementation for EVERY 202: the composer's own POST and an ACK
 * originating outside it (`useSteerRecovery`'s retry, for a steer that already
 * failed once) both resolve through this, instead of approximating each other.
 *
 * @returns true when the caller must route the steer into the queue.
 */
export function resolveAcknowledgedSteer(
  { snapshot, set }: Pick<CallbackInterface, 'snapshot' | 'set'>,
  conversationId: string,
  localId: string,
  steer: PendingSteer,
  ordinaryRunOver: boolean,
): boolean {
  const applied = snapshot.getLoadable(store.appliedSteerIdsByConvoId(conversationId)).getValue();
  const alreadyApplied = applied.includes(steer.steerId) || applied.includes(localId);
  const alreadyAccepted = snapshot
    .getLoadable(store.acceptedSteerClientIdsByConvoId(conversationId))
    .getValue()
    .includes(localId);
  const activeEpoch = snapshot
    .getLoadable(store.activeGenerationCreatedAtByConvoId(conversationId))
    .getValue();
  /** A replacement can already be submitting when an older generation's
   * delayed 202 arrives. Ordinary submission state alone would re-mint the old
   * chip after replacement reconciliation, with no old apply event left to
   * settle it. Every POST reaching here captured a non-null source epoch before
   * dispatch, so either a mismatch or a later clear proves that source
   * generation is no longer active. */
  const runReplaced =
    steer.generationCreatedAt != null &&
    (activeEpoch == null || steer.generationCreatedAt !== activeEpoch);
  const runOver = ordinaryRunOver || runReplaced;
  set(store.acceptedSteerClientIdsByConvoId(conversationId), (prev) =>
    appendAppliedSteerIds(prev, [localId]),
  );
  set(store.pendingSteersByConvoId(conversationId), (prev) => {
    const local = prev.find((item) => item.steerId === localId);
    let acknowledged = steer;
    if ((local?.preemptRevision ?? 0) > (steer.preemptRevision ?? 0)) {
      const { preempt: _stalePreempt, ...withoutStaleLabel } = steer;
      acknowledged = {
        ...withoutStaleLabel,
        ...(local?.preempt === true && { preempt: true }),
        preemptRevision: local?.preemptRevision,
      };
    }
    const next = prev.filter((item) => item.steerId !== localId);
    // Upsert: an SSE reconnect may have reseeded the chip under the server id
    // already; appending again would duplicate it.
    const alreadySeeded = next.some((item) => item.steerId === steer.steerId);
    return alreadyApplied || alreadyAccepted || runOver || alreadySeeded
      ? next
      : [...next, acknowledged];
  });
  /** `alreadyAccepted` can come from the correlation update that precedes the
   * delayed HTTP response; it proves server ownership, not delivery. Once the
   * source epoch is over/replaced we still must recover it. */
  if (alreadyApplied || !runOver) {
    return false;
  }
  // The server accepted but this run is already terminal. Its terminal close
  // may have parked the item, so the caller must route it through the recovery
  // converter (deterministic next-turn id), not an ordinary editable queue row.
  return true;
}

/** The message the pause predicates judge: the caller's resolved active-branch
 *  tail when it passed one, else the latest assistant in the supplied cache.
 *  Passing the tail is what stops a cached sibling branch from deciding for
 *  the branch on screen. */
function resolvePauseSubject(
  messagesOrMessage: TMessage[] | TMessage | null | undefined,
  activeTail?: TMessage | null,
): TMessage | null | undefined {
  if (activeTail !== undefined) {
    return activeTail;
  }
  if (!Array.isArray(messagesOrMessage)) {
    return messagesOrMessage;
  }
  for (let index = messagesOrMessage.length - 1; index >= 0; index--) {
    if (messagesOrMessage[index].isCreatedByUser === false) {
      return messagesOrMessage[index];
    }
  }
  return null;
}

/** True when the latest assistant message carries an unresolved tool approval:
 *  the run is (or is about to be) paused, so a steer POST would 409.
 *
 *  Pass the active branch tail whenever it has been resolved; without it this
 *  falls back to array order over the cache. */
export function hasLiveToolApproval(
  messagesOrMessage: TMessage[] | TMessage | null | undefined,
  activeTail?: TMessage | null,
): boolean {
  const message = resolvePauseSubject(messagesOrMessage, activeTail);
  if (message?.isCreatedByUser !== false) {
    return false;
  }
  const content = message.content;
  if (!Array.isArray(content)) {
    return false;
  }
  return content.some((part: TMessageContentParts | undefined) => {
    if (part?.type !== ContentTypes.TOOL_CALL) {
      return false;
    }
    const toolCall = part[ContentTypes.TOOL_CALL] as
      | { approval?: unknown; output?: string | null }
      | undefined;
    return toolCall?.approval != null && (toolCall.output?.length ?? 0) === 0;
  });
}

interface LiveMessageState {
  approval: boolean;
  parentMessageId?: string;
}

function selectLiveMessageState(message: TMessage | null): LiveMessageState {
  let parentMessageId: string | undefined;
  if (message?.isCreatedByUser === false && typeof message.messageId === 'string') {
    parentMessageId = message.clientQueueParentMessageId ?? message.messageId;
  }
  return { approval: hasLiveToolApproval(message), parentMessageId };
}

function compareQueuedMessages(a: QueuedMessage, b: QueuedMessage): number {
  const priority = Number(b.priority ?? false) - Number(a.priority ?? false);
  if (priority !== 0) {
    return priority;
  }
  const aServerOrder = a.server?.revision;
  const bServerOrder = b.server?.revision;
  if (aServerOrder != null && bServerOrder != null && aServerOrder !== bServerOrder) {
    return aServerOrder - bServerOrder;
  }
  if (a.server != null && b.server == null) {
    return -1;
  }
  if (a.server == null && b.server != null) {
    return 1;
  }
  return a.createdAt - b.createdAt;
}

function queuedTurnCreatedAt(receipt: AgentQueuedTurnReceipt): number {
  const createdAt = Date.parse(receipt.createdAt);
  return Number.isFinite(createdAt) ? createdAt : 0;
}

type QueuedTurnReceiptSource = 'snapshot' | 'enqueue' | 'direct';

function isAdmissionIndeterminateReceipt(receipt: AgentQueuedTurnReceipt): boolean {
  return (
    receipt.failure?.code === 'ADMISSION_INDETERMINATE' &&
    (receipt.status === 'claimed' || receipt.status === 'dead')
  );
}

function settledEvidenceForReceipt(
  receipt: AgentQueuedTurnReceipt,
): SettledQueuedTurnReceipt | undefined {
  if (
    receipt.status === 'admitted' &&
    (receipt.effectivePredecessorCreatedAt != null || receipt.rootPredecessor === true)
  ) {
    return {
      clientRequestId: receipt.clientRequestId,
      status: 'admitted',
      ...(receipt.effectivePredecessorCreatedAt != null && {
        effectivePredecessorCreatedAt: receipt.effectivePredecessorCreatedAt,
      }),
      ...(receipt.rootPredecessor === true && { rootPredecessor: true }),
    };
  }
  if (receipt.status === 'admitted') {
    return {
      clientRequestId: receipt.clientRequestId,
      status: 'admitted_pending_boundary',
    };
  }
  if (isAdmissionIndeterminateReceipt(receipt)) {
    return { clientRequestId: receipt.clientRequestId, status: 'indeterminate' };
  }
  if (receipt.status === 'cancelled') {
    return { clientRequestId: receipt.clientRequestId, status: 'cancelled' };
  }
  if (receipt.status === 'dead') {
    return { clientRequestId: receipt.clientRequestId, status: 'dead' };
  }
  return undefined;
}

/** Client receipt knowledge is a monotonic evidence lattice. Enqueue is the
 * only source that can carry a pre-scheduling snapshot, so it never weakens
 * evidence already observed by GET/direct settlement. Indeterminate evidence
 * can advance only through a later authoritative terminal observation. */
function mergeSettledQueuedTurnEvidence(
  existing: SettledQueuedTurnReceipt | undefined,
  receipt: AgentQueuedTurnReceipt,
  source: QueuedTurnReceiptSource,
): SettledQueuedTurnReceipt | undefined {
  const incoming = settledEvidenceForReceipt(receipt);
  if (existing == null) {
    return incoming;
  }
  if (existing.status === 'admitted_pending_boundary' && incoming?.status === 'admitted') {
    return incoming;
  }
  if (
    existing.status === 'indeterminate' &&
    source !== 'enqueue' &&
    incoming != null &&
    incoming.status !== 'indeterminate'
  ) {
    return incoming;
  }
  return existing;
}

function toQueuedTurnFileRefs(files: TMessage['files']): TAgentQueuedTurnFileRef[] | undefined {
  const refs = (files ?? []).flatMap((file): TAgentQueuedTurnFileRef[] => {
    if (typeof file.file_id !== 'string' || file.file_id.length === 0) {
      return [];
    }
    return [
      {
        file_id: file.file_id,
        ...(file.type != null && { type: file.type }),
        ...(file.filepath != null && { filepath: file.filepath }),
        ...(file.filename != null && { filename: file.filename }),
        ...(file.llmDeliveryPath != null && { llmDeliveryPath: file.llmDeliveryPath }),
        ...(file.height != null && { height: file.height }),
        ...(file.width != null && { width: file.width }),
        ...(file.bytes != null && { bytes: file.bytes }),
      },
    ];
  });
  return refs.length > 0 ? refs : undefined;
}

export { hydrateFileDeliveryMetadata as mergeQueuedTurnFileMetadata } from '~/utils/files';

function reconcileServerQueuedTurns(
  previous: QueuedMessage[],
  receipts: AgentQueuedTurnReceipt[],
  settledByRequestId: ReadonlyMap<string, SettledQueuedTurnReceipt>,
  authoritativeSnapshot = true,
  storedFiles?: Parameters<typeof hydrateFileDeliveryMetadata>[2],
): QueuedMessage[] {
  const previousByClientRequestId = new Map(
    previous.flatMap((item) =>
      item.clientRequestId != null ? [[item.clientRequestId, item] as const] : [],
    ),
  );
  const observedClientRequestIds = new Set(receipts.map((receipt) => receipt.clientRequestId));
  const projected = receipts.flatMap((receipt): QueuedMessage[] => {
    const settled = settledByRequestId.get(receipt.clientRequestId);
    const admissionIndeterminate = isAdmissionIndeterminateReceipt(receipt);
    if (settled?.status === 'admitted' || settled?.status === 'cancelled') {
      return [];
    }
    const optimistic = previousByClientRequestId.get(receipt.clientRequestId);
    if (
      (settled?.status === 'dead' ||
        settled?.status === 'admitted_pending_boundary' ||
        (settled?.status === 'indeterminate' && !admissionIndeterminate)) &&
      receipt.status !== 'dead' &&
      receipt.status !== 'admitted'
    ) {
      return optimistic == null ? [] : [optimistic];
    }
    const boundaryPending = receipt.status === 'admitted';
    let status: NonNullable<QueuedMessage['server']>['status'] = 'rejected';
    if (admissionIndeterminate) {
      status = 'indeterminate';
    } else if (boundaryPending) {
      status = 'uncertain';
    } else if (receipt.status === 'queued' || receipt.status === 'claimed') {
      status = receipt.status;
    }
    const files = hydrateFileDeliveryMetadata(receipt.files, optimistic?.files, storedFiles);
    return [
      {
        id: optimistic?.id ?? receipt.clientRequestId,
        text: receipt.text,
        createdAt: queuedTurnCreatedAt(receipt),
        clientRequestId: receipt.clientRequestId,
        parentMessageId: receipt.parentMessageId,
        ...(receipt.expectedPredecessorCreatedAt != null && {
          expectedPredecessorCreatedAt: receipt.expectedPredecessorCreatedAt,
        }),
        ...(files != null && files.length > 0 && { files }),
        ...(receipt.quotes != null && receipt.quotes.length > 0 && { quotes: receipt.quotes }),
        ...(receipt.manualSkills != null &&
          receipt.manualSkills.length > 0 && {
            manualSkills: receipt.manualSkills,
          }),
        ...(receipt.reasoningOverride != null && {
          reasoningOverride: receipt.reasoningOverride,
        }),
        ...(receipt.priority === true && { priority: true }),
        server: {
          id: receipt.queuedTurnId,
          status,
          revision: receipt.revision,
          ...(boundaryPending && {
            uncertainSince: optimistic?.server?.uncertainSince ?? Date.now(),
          }),
          ...(receipt.position != null && { position: receipt.position }),
          ...(receipt.failure?.code != null && { errorCode: receipt.failure.code }),
          ...(receipt.failure?.message != null && { errorMessage: receipt.failure.message }),
        },
      },
    ];
  });
  const retained = previous.filter((item) => {
    if (item.server == null) {
      return true;
    }
    const settled =
      item.clientRequestId == null ? undefined : settledByRequestId.get(item.clientRequestId);
    if (settled?.status === 'admitted' || settled?.status === 'cancelled') {
      return false;
    }
    if (settled?.status === 'dead' || settled?.status === 'admitted_pending_boundary') {
      return item.clientRequestId == null || !observedClientRequestIds.has(item.clientRequestId);
    }
    if (item.clientRequestId == null || observedClientRequestIds.has(item.clientRequestId)) {
      return false;
    }
    if (!authoritativeSnapshot) {
      return true;
    }
    return (
      item.server.status === 'sending' ||
      item.server.status === 'uncertain' ||
      item.server.status === 'indeterminate' ||
      item.server.status === 'rejected'
    );
  });
  return [...retained, ...projected].sort(compareQueuedMessages);
}
/**
 * The ONE during-run pause predicate. Both an unresolved tool approval and a
 * live `ask_user_question` suspend the generation while keeping its submission
 * slot occupied, so a steer POST would 409 in either case.
 *
 * Shared by the composer and the in-thread pending steers so a control is
 * never enabled on one surface while the other correctly refuses. Callers
 * should pass the active branch tail when they have resolved it; this prevents
 * a cached sibling from changing the result.
 */
export function hasLiveRunPause(
  messagesOrMessage: TMessage[] | TMessage | null | undefined,
  activeTail?: TMessage | null,
): boolean {
  /* Legacy callers hand over the whole cache without a resolved tail; keep
     scanning it for them, but once a caller resolves the active branch only
     that branch decides. */
  const questionSource =
    activeTail === undefined && Array.isArray(messagesOrMessage)
      ? messagesOrMessage
      : [resolvePauseSubject(messagesOrMessage, activeTail)].filter(
          (message): message is TMessage => message != null,
        );
  return (
    hasLiveToolApproval(messagesOrMessage, activeTail) ||
    findLiveAskUserQuestion(questionSource) != null
  );
}

